import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { parseArgs } from "node:util";
import Ajv, { _, Name } from "ajv";
import standaloneCode from "ajv/dist/standalone/index.js";
import { compile } from "json-schema-to-typescript";
import { format } from "prettier";

const SCHEMA_ID = "https://reviewq.invalid/contracts/v1.schema.json";
const GENERATED = "// Generated by make contracts.\n";
const MAX_SOURCE_LINES = 900;
const UTF8_ENCODER = _`new TextEncoder()`;
const UTC_FORMAT = new Name("utcTimestamp");

const { values: args } = parseArgs({
  options: {
    schema: { type: "string" },
    out: { type: "string" },
  },
});
if (!args.schema || !args.out) {
  throw new Error("Usage: generate-contracts.mjs --schema <schema> --out <directory>");
}

const schema = JSON.parse(await readFile(args.schema, "utf8"));
const responseRefs = Object.entries(schema["x-reviewq-responses"]);
const types = await compile(
  {
    title: "Responses",
    type: "object",
    properties: Object.fromEntries(responseRefs.map(([name, $ref]) => [name, { $ref }])),
    required: responseRefs.map(([name]) => name),
    additionalProperties: false,
    definitions: schema.definitions,
  },
  "Responses",
  {
    bannerComment: GENERATED.trimEnd(),
    format: false,
    unreachableDefinitions: false,
    $refOptions: { resolve: { external: false } },
  },
);
const predicates = generatePredicates(schema, responseRefs);
const validatorIndex = predicates
  .map(({ name, file }) => `export { ${name} } from "./${file}";`)
  .join("\n");
const declarations = [
  GENERATED,
  `import type { ${responseRefs.map(([name]) => name).join(", ")} } from "./contracts.js";`,
  "",
  ...responseRefs.map(([name]) => `export function is${name}(value: unknown): value is ${name};`),
].join("\n");

const files = await Promise.all(
  [
    ["contracts.ts", types],
    ["validators.mjs", GENERATED + validatorIndex],
    ["validators.d.mts", declarations],
    ...predicates.map(({ file, source }) => [file, source]),
  ].map(async ([name, source]) => {
    const formatted = await format(source, { filepath: name });
    if (formatted.split("\n").length - 1 > MAX_SOURCE_LINES) {
      throw new Error(`${name} exceeds ${MAX_SOURCE_LINES} physical lines`);
    }
    return [name, formatted];
  }),
);

await Promise.all(
  files.map(async ([name, bytes]) => {
    const path = join(args.out, name);
    await mkdir(dirname(path), { recursive: true });
    await writeFile(path, bytes);
  }),
);

function generatePredicates(schema, refs) {
  const ajv = new Ajv({
    strict: true,
    ownProperties: true,
    messages: false,
    code: {
      esm: true,
      source: true,
      lines: true,
      formats: _`{ "date-time": ${UTC_FORMAT} }`,
    },
  });
  ajv.addFormat("date-time", isUtcTimestamp);
  ajv.addKeyword("x-reviewq-responses");
  ajv.addKeyword({
    keyword: "maxUtf8Bytes",
    type: "string",
    schemaType: "number",
    metaSchema: { type: "integer", minimum: 0 },
    code(context) {
      const { data, gen, schemaCode: limit } = context;
      const encoder = gen.scopeValue("func", { ref: UTF8_ENCODER, code: UTF8_ENCODER });
      context.fail(_`${data}.length > ${limit} || ${encoder}.encode(${data}).length > ${limit}`);
    },
  });
  ajv.addSchema(schema, SCHEMA_ID);
  return refs.map(([typeName, ref]) => {
    const name = `is${typeName}`;
    const fileName = typeName.replace(/([a-z0-9])([A-Z])/g, "$1-$2").toLowerCase();
    return {
      name,
      file: `validators/${fileName}.mjs`,
      source:
        GENERATED +
        `const ${UTC_FORMAT} = ${isUtcTimestamp.toString()};\n` +
        standaloneCode(ajv, { [name]: SCHEMA_ID + ref }),
    };
  });
}

function isUtcTimestamp(value) {
  const date = new Date(value);
  return Number.isFinite(date.getTime()) && date.toISOString() === value;
}
