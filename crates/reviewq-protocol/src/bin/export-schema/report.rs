use std::error::Error;
use std::io::{self, Write};

use reviewq_protocol::GitShaDto;
use reviewq_protocol::reports::{
    FindingBasis, FindingBasisKind, FindingLocation, Handoff, REPORT_HANDOFF_DESCRIPTION,
    ReportHandoffInput, ReportRevision, ReportSource, ReportVerdict, StructuredFinding,
    StructuredReport,
};
use schemars::generate::SchemaSettings;

pub(super) fn export(mode: &str) -> Result<(), Box<dyn Error>> {
    let mut output = io::stdout().lock();
    match mode {
        "--report-handoff-schema" | "--claude-report-handoff" => {
            let mut schema = SchemaSettings::draft07()
                .for_deserialize()
                .into_generator()
                .into_root_schema_for::<ReportHandoffInput>()
                .to_value();
            // The native tool inputs are decoded as UTF-8. UTF-16 surrogate
            // code units cannot reach this schema, and Rust regex rejects them.
            for definition in ["ResourceIdDto", "FindingIdDto", "DiscussionIdDto"] {
                let pattern = &mut schema["definitions"][definition]["pattern"];
                if let Some(value) = pattern.as_str() {
                    *pattern = serde_json::Value::String(value.replace(r"\ud800-\udfff", ""));
                }
            }
            if mode == "--claude-report-handoff" {
                writeln!(
                    output,
                    "// Generated by reviewq-protocol. Run make contracts."
                )?;
                write!(output, "export const description = ")?;
                serde_json::to_writer(&mut output, REPORT_HANDOFF_DESCRIPTION)?;
                write!(output, ";\nexport const inputSchema = ")?;
            }
            serde_json::to_writer_pretty(&mut output, &schema)?;
            if mode == "--claude-report-handoff" {
                write!(output, ";")?;
            }
        }
        "--report-handoff-example" => serde_json::to_writer_pretty(&mut output, &example())?,
        _ => return Err(format!("Unknown contract export mode: {mode}").into()),
    }
    writeln!(output)?;
    Ok(())
}

fn example() -> ReportHandoffInput {
    ReportHandoffInput {
        handoff: Handoff::Final {
            source: ReportSource::Response,
            revision: ReportRevision::Exact {
                sha: GitShaDto::new("000000000000000000000000000000000000000a").unwrap(),
            },
            verdict: ReportVerdict::RequestChanges,
            report: Some(StructuredReport {
                version: 1,
                findings: vec![StructuredFinding {
                    id: "F-01".into(),
                    title: "Retry writes the same invoice twice".into(),
                    severity: "high".into(),
                    blocking: true,
                    location: Some(FindingLocation {
                        path: "src/invoices.rs".into(),
                        line: Some(74),
                    }),
                    consequence: "A lost acknowledgement can create a duplicate invoice.".into(),
                    evidence: FindingBasis {
                        kind: FindingBasisKind::Observed,
                        text: "The retry uses a fresh key after the original insert commits."
                            .into(),
                    },
                }],
            }),
            amends: None,
            finding_changes: Vec::new(),
            assessments: Vec::new(),
        },
    }
}
