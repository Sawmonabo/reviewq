//! The ledger tool contract: the six input schemas, their filled example and the module the
//! Claude plugin loads. Every mode first proves the example against the schemas it generates.

use std::error::Error;
use std::io::{self, Write};

use reviewq_protocol::followups::NextAction;
use reviewq_protocol::ledger::{
    AssessFinding, FinishReview, LEDGER_TOOLS, LedgerTool, NeedsInput, NoteSection, RecordFinding,
    RecordNote, ReviewLedger, validate_against,
};
use reviewq_protocol::reports::{
    Assessment, FindingBasis, FindingBasisKind, FindingConclusion, FindingLocation, FindingSection,
    ReportRevision, Severity, Verdict,
};
use reviewq_protocol::{DiscussionIdDto, FindingIdDto, GitShaDto};
use schemars::JsonSchema;
use schemars::generate::SchemaSettings;
use serde_json::{Map, Value, json};

pub(super) fn export(mode: &str) -> Result<(), Box<dyn Error>> {
    let schemas = LEDGER_TOOLS
        .map(|tool| (tool, input_schema(tool)))
        .into_iter()
        .collect::<Vec<_>>();
    let examples = examples()?;
    if !examples.iter().map(|(tool, _)| *tool).eq(LEDGER_TOOLS) {
        return Err("give one example per ledger tool, in table order".into());
    }
    for ((tool, schema), (_, example)) in schemas.iter().zip(&examples) {
        if let Err(errors) = validate_against(schema, *tool, example) {
            return Err(format!("the {} example is refused: {errors:?}", tool.name()).into());
        }
    }
    let mut output = io::stdout().lock();
    match mode {
        "--ledger-tools-schema" => serde_json::to_writer_pretty(&mut output, &by_name(schemas))?,
        "--ledger-tools-example" => serde_json::to_writer_pretty(&mut output, &by_name(examples))?,
        "--claude-ledger-tools" => {
            let tools: Vec<_> = schemas
                .iter()
                .map(|(tool, schema)| {
                    json!({
                        "name": tool.name(),
                        "description": tool.description(),
                        "deadlineMs": tool.deadline().as_secs() * 1000,
                        "inputSchema": schema,
                    })
                })
                .collect();
            writeln!(
                output,
                "// Generated by reviewq-protocol. Run make contracts."
            )?;
            write!(output, "export const ledgerTools = ")?;
            serde_json::to_writer_pretty(&mut output, &tools)?;
            write!(output, ";")?;
        }
        _ => return Err(format!("Unknown contract export mode: {mode}").into()),
    }
    writeln!(output)?;
    Ok(())
}

fn input_schema(tool: LedgerTool) -> Value {
    match tool {
        LedgerTool::RecordFinding => root::<RecordFinding>(),
        LedgerTool::AssessFinding => root::<AssessFinding>(),
        LedgerTool::RecordNote => root::<RecordNote>(),
        LedgerTool::ReviewLedger => root::<ReviewLedger>(),
        LedgerTool::FinishReview => root::<FinishReview>(),
        LedgerTool::NeedsInput => root::<NeedsInput>(),
    }
}

/// One self-contained Draft 7 schema, which a host registers as a tool's input schema as is.
fn root<T: JsonSchema>() -> Value {
    let mut schema = SchemaSettings::draft07()
        .for_deserialize()
        .into_generator()
        .into_root_schema_for::<T>()
        .to_value();
    adapt_strings(&mut schema);
    schema
}

/// Native tool inputs arrive as UTF-8, so UTF-16 surrogates cannot reach these patterns, and
/// the Rust regex engine rejects them. A string bounded only in bytes also gets that bound as
/// its character maximum, which the model reads. A description wrapped across doc-comment lines
/// reads as one paragraph.
fn adapt_strings(schema: &mut Value) {
    match schema {
        Value::Object(object) => {
            if let Some(Value::String(description)) = object.get_mut("description") {
                *description = description
                    .split("\n\n")
                    .map(|paragraph| paragraph.replace('\n', " "))
                    .collect::<Vec<_>>()
                    .join("\n\n");
            }
            if let Some(Value::String(pattern)) = object.get_mut("pattern") {
                *pattern = pattern.replace(r"\ud800-\udfff", "");
            }
            if let Some(bytes) = object.get("maxUtf8Bytes").cloned()
                && !object.contains_key("maxLength")
            {
                object.insert("maxLength".into(), bytes);
            }
            object.values_mut().for_each(adapt_strings);
        }
        Value::Array(items) => items.iter_mut().for_each(adapt_strings),
        _ => (),
    }
}

fn by_name(entries: Vec<(LedgerTool, Value)>) -> Map<String, Value> {
    entries
        .into_iter()
        .map(|(tool, value)| (tool.name().to_owned(), value))
        .collect()
}

/// One valid input per tool, after the spec's worked calls.
fn examples() -> Result<Vec<(LedgerTool, Value)>, Box<dyn Error>> {
    let finding = || FindingIdDto::new("F-01").ok_or("example finding ID");
    let record_finding = RecordFinding {
        id: None,
        expected_revision: None,
        title: Some("Retry writes the same invoice twice".into()),
        severity: Some(Severity::P1),
        blocking: Some(true),
        section: Some(FindingSection::Functional),
        category: None,
        locations: Some(vec![FindingLocation {
            path: "src/invoices.rs".into(),
            line: Some(74),
        }]),
        issue: Some(
            "The retry builds a fresh idempotency key after the first insert commits.".into(),
        ),
        consequence: Some("A lost acknowledgement creates a duplicate invoice.".into()),
        evidence: Some(FindingBasis {
            kind: FindingBasisKind::Observed,
            text: "Replaying the request after a dropped reply inserted two rows.".into(),
        }),
        proposed_comment: None,
        details: None,
    };
    let assess_finding = AssessFinding {
        id: finding()?,
        expected_revision: 1,
        outcome: FindingConclusion::Fixed,
        reason: "The retry now reuses the stored key.".into(),
        discussion_ids: Vec::new(),
        checked_sha: None,
    };
    let record_note = RecordNote {
        section: NoteSection::Summary,
        title: None,
        body: "The MR retries invoice creation when the payment provider times out.".into(),
        expected_revision: None,
    };
    let review_ledger = ReviewLedger {
        ids: vec![finding()?],
        ..ReviewLedger::default()
    };
    let finish_review = FinishReview {
        verdict: Some(Verdict::RequestChanges),
        revision: Some(ReportRevision {
            sha: Some(
                GitShaDto::new("aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa").ok_or("example SHA")?,
            ),
            reason: None,
        }),
        full_review: false,
        assessments: Vec::new(),
    };
    let needs_input = NeedsInput {
        reason: "Should a retried invoice keep its original number?".into(),
    };
    // A selected-thread close from the spec, kept here so the assessment shape is exercised too.
    let selected_thread_close = FinishReview {
        verdict: None,
        revision: None,
        full_review: false,
        assessments: vec![Assessment {
            discussion_id: DiscussionIdDto::new("D7").ok_or("example discussion ID")?,
            conclusion: FindingConclusion::StillPresent,
            reason: "The selected guard still permits an empty list. The original note already asks for that guard.".into(),
            finding_ids: vec![finding()?],
            next_action: NextAction::WaitingAuthor,
        }],
    };
    if let Err(errors) = validate_against(
        &input_schema(LedgerTool::FinishReview),
        LedgerTool::FinishReview,
        &serde_json::to_value(&selected_thread_close)?,
    ) {
        return Err(format!("the selected-thread example is refused: {errors:?}").into());
    }
    Ok(vec![
        (
            LedgerTool::RecordFinding,
            serde_json::to_value(record_finding)?,
        ),
        (
            LedgerTool::AssessFinding,
            serde_json::to_value(assess_finding)?,
        ),
        (LedgerTool::RecordNote, serde_json::to_value(record_note)?),
        (
            LedgerTool::ReviewLedger,
            serde_json::to_value(review_ledger)?,
        ),
        (
            LedgerTool::FinishReview,
            serde_json::to_value(finish_review)?,
        ),
        (LedgerTool::NeedsInput, serde_json::to_value(needs_input)?),
    ])
}
